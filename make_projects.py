def склон(n, одна, две, много):
    n = abs(n) % 100
    if 11 <= n <= 14: return много
    n %= 10
    if n == 1: return одна
    if 2 <= n <= 4: return две
    return много


def месяц_год(d):
    return f'{МЕСЯЦ_ИМ[d.month - 1]} {d.year}'


def период(даты):
    if not даты: return ''
    a, b = min(даты), max(даты)
    if месяц_год(a) == месяц_год(b): return месяц_год(a)
    return f'{месяц_год(a)} — {месяц_год(b)}'


БАТАРЕЯ = re.compile(r'^(\d+)\s*[VВв]\s*(\d+)')


def ттх(строки):
    """Напряжение и ёмкость из графы «Батарея»: «24V150» → (24, 150)."""
    пары = []
    for r in строки:
        m = БАТАРЕЯ.match(str(r.get('Батарея') or '').strip())
        if m: пары.append((int(m.group(1)), int(m.group(2))))
    return пары


def фраза_ттх(пары):
    if not пары: return ''
    v = sorted({p[0] for p in пары}); a = sorted({p[1] for p in пары})
    напр = f'{v[0]} В' if len(v) == 1 else f'{v[0]}–{v[-1]} В'
    ёмк = f'{a[0]} А·ч' if len(a) == 1 else f'{a[0]}–{a[-1]} А·ч'
    return f'{напр} {ёмк}'


def оснастка(доп_строки):
    куски = []
    # Артикул ЗУ в файле иногда тянет за собой расшифровку в скобках —
    # «TOR6111 (ТРЕХФАЗНОЕ, 48В 150A. LIFEPO4, 15S, 412AH)». В карточке
    # нужен артикул, остальное шум.
    зу = sorted({re.split(r'\s*\(', str(r['ЗУ']).strip())[0] for r in доп_строки
                 if r.get('ЗУ') and str(r['ЗУ']).strip() not in ('-', '—')})
    мод = sorted({str(r['Модификации']).strip().lower() for r in доп_строки
                  if r.get('Модификации') and str(r['Модификации']).strip().lower() != 'стандарт'})
    ут = [r for r in доп_строки if r.get('Утяжелитель') not in (None, '', '-')]
    if зу:
        куски.append(f'Зарядные {"устройства " if len(зу) > 1 else ""}' +
                     ', '.join(зу[:2]) + ('' if len(зу) <= 2 else ' и другие'))
    if ут:
        веса = [str(r['Утяжелитель']).strip() for r in ут]
        # В графе встречается и голый вес, и фраза «Балласт 919 кг» целиком.
        if len(set(веса)) == 1:
            в = веса[0]
            куски.append(в if re.match(r'^[А-ЯЁа-яё]', в)
                         else f'грузокомпенсатор{"ы" if len(ут) > 1 else ""} {в}')
        else:
            куски.append('грузокомпенсаторы разного веса')
    if мод:
        куски.append('исполнение ' + ', '.join(мод))
    if not куски: return ''
    s = '; '.join(куски)
    return s[0].upper() + s[1:] + '.'


def текст(лин, кол, пары, доп_строки, номер, всего, место):
    ч = ЧИСЛА.get(кол, str(кол))
    тт = фраза_ттх(пары)
    if лин == 'тяговые':
        шт = склон(кол, 'батарея', 'батареи', 'батарей')
        первая = f'{ч.capitalize()} {шт}' + (f' {тт}' if тт else '') + '.'
    elif лин == 'скиф':
        шт = склон(кол, 'станция', 'станции', 'станций')
        модели = sorted({str(r.get('Модель') or '').strip()
                         for r in доп_строки if str(r.get('Модель') or '').startswith('СКИФ')})
        первая = f'{ч.capitalize()} {шт}' + (f' {", ".join(модели)}' if модели else '') + '.'
    elif лин == 'хранитель':
        исп = sorted({m.group(1) for r in доп_строки
                      if (m := re.search(r'Хранитель\s+([А-ЯЁ][а-яё]+)', str(r.get('Модель') or '')))})
        первая = ('Хранитель в исполнении «' + '», «'.join(исп) + '»'
                  if исп else 'Система накопления энергии')
        первая += (f', {тт}.' if тт else '.')
    else:
        шт = склон(кол, 'система', 'системы', 'систем')
        первая = f'{ч.capitalize()} {шт}' + (f' {тт}' if тт else '') + '.'

    части = [первая]
    о = оснастка(доп_строки)
    if о: части.append(о)
    if место: части.append(f'Площадка: {место}.')
    if всего > 1:
        п = ПОРЯДКОВЫЕ.get(номер, f'{номер}-я')
        сколько = РОДИТЕЛЬНЫЙ.get(всего, str(всего))
        части.append(f'{п} из {сколько} поставок этому заказчику.')
    return ' '.join(части)


