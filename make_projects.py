def дата(v):
    if isinstance(v, datetime.datetime):
        return v.date()
    if isinstance(v, datetime.date):
        return v
    return None


def собрать_эпизоды(реестр, серийные):
    """Эпизод — объект плюс группа отгрузок, идущих подряд.

    Строка «Реестра» — одна партия, то есть одна отгрузка; группируем их
    по объекту и режем там, где между отгрузками больше ПОРОГ дней.
    Решение владельца 28.10.2026: дробность «площадка + обращение».
    """
    запас = collections.defaultdict(list)
    for s in серийные:
        d = дата(s.get('Реализация'))
        if d:
            запас[(объект(s), норм(s.get('Модель')))].append(d)

    по_объекту = collections.defaultdict(list)
    for r in реестр:
        d = дата(r.get(ГРАФА_ДАТЫ))
        if not d:
            рез = запас.get((объект(r), норм(r.get('Модель'))))
            d = min(рез) if рез else None
        r['_дата'] = d
        по_объекту[(линейка(r), объект(r))].append(r)

    эпизоды = []
    for (лин, об), строки in по_объекту.items():
        с_датой = sorted([r for r in строки if r['_дата']], key=lambda r: r['_дата'])
        без = [r for r in строки if not r['_дата']]
        текущий = []
        for r in с_датой:
            if текущий and r['_дата'] - текущий[-1]['_дата'] > ПОРОГ:
                эпизоды.append((лин, об, текущий)); текущий = []
            текущий.append(r)
        if текущий:
            эпизоды.append((лин, об, текущий))
        if без:
            эпизоды.append((лин, об, без))
    return эпизоды


