def читать(ws, шапка=3):
    ключи = [ws.cell(шапка, c).value for c in range(1, ws.max_column + 1)]
    out = []
    for r in range(шапка + 1, ws.max_row + 1):
        стр = {(k or f'кол{c}'): ws.cell(r, c).value
               for c, k in enumerate(ключи, start=1)}
        # ГРАБЛИ №17: строку выбрасываем, только если пусты ВСЕ её графы.
        if all(v in (None, '') for v in стр.values()):
            continue
        out.append(стр)
    return out


