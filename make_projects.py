def обновить_цифры(d, items, slug):
    """Цифры в шапке считаются по карточкам этой же страницы.

    Пока они стояли руками, они разъезжались с данными при каждой правке:
    на Энергопотоке висело «22 системы на семи объектах», когда объектов
    было одиннадцать, а систем тринадцать.
    """
    блок = next((b for b in d['blocks'] if b.get('type') == 'figs'), None)
    if not блок or slug not in ПОДПИСИ:
        return None
    шт = sum(int(m.group(1)) for i in items if (m := re.search(r'(\d+) шт', i['meta'])))
    # Считаем по ключу объекта: несколько «частных заказчиков» — это
    # несколько разных домов, а не один заказчик с четырьмя карточками.
    объекты = len({i['_объект'] for i in items})
    годы = sorted({m.group(1) for i in items
                   if (m := re.search(r'(20\d\d)', i['meta'])) and m.group(1) < '2027'})
    п = ПОДПИСИ[slug]
    блок['items'] = [
        {'value': str(шт), 'label': п[0]},
        {'value': str(объекты), 'label': п[1]},
        {'value': f'{годы[0]}–{годы[-1]}' if годы else '—', 'label': п[2]},
    ]
    return (шт, объекты, годы)


def main(путь):
    global ОРГАНИЗАЦИИ, МНОГО_МЕСТ, ПЕРЕИМ
    wb = openpyxl.load_workbook(путь, data_only=True)
    реестр, серийные = читать(wb['Реестр']), читать(wb['Серийные'])
    print(f'прочитано: Реестр {len(реестр)}, Серийные {len(серийные)}')

    ОРГАНИЗАЦИИ = set(json.loads(
        pathlib.Path('_sources/организации.json').read_text(encoding='utf-8'))['организации'])
    места = collections.defaultdict(set)
    for r in реестр + серийные:
        имя = str(r.get('Клиент') or r.get('Покупатель') or '').strip()
        м = str(r.get('Место_ эксплуатации') or '').strip()
        if м: места[имя].add(м)
    МНОГО_МЕСТ = {к for к, v in места.items() if len(v) > 1}
    ПЕРЕИМ = имена()
    print('заказчики с несколькими площадками:', ', '.join(sorted(МНОГО_МЕСТ)) or 'нет')

    реестр = [r for r in реестр
              if str(r.get('Клиент') or r.get('Покупатель') or '').strip() not in ИСКЛЮЧИТЬ]
    серийные = [r for r in серийные
                if str(r.get('Клиент') or r.get('Покупатель') or '').strip() not in ИСКЛЮЧИТЬ]

    эпизоды = собрать_эпизоды(реестр, серийные)
    тексты = json.loads(ТЕКСТЫ.read_text(encoding='utf-8')) if ТЕКСТЫ.exists() else {}
    стр = карточки(эпизоды, имена(), тексты)

    for slug, items in стр.items():
        f = CONTENT / f'{slug}.json'
        d = json.loads(f.read_text(encoding='utf-8'))
        # Сверху свежие, снизу давние (решение владельца 28.10.2026).
        items.sort(key=lambda c: c['_ключ'], reverse=True)
        блок = next(b for b in d['blocks'] if b.get('type') == 'cases')
        блок['items'] = items
        блок['шаг'] = ШАГ
        блок['id'] = блок.get('id') or 'cases'
        сводка = обновить_цифры(d, items, slug)
        for c in items:
            c.pop('_ключ', None); c.pop('_объект', None)
        # Хвостовые таблицы больше не нужны: каждая поставка — карточка.
        d['blocks'] = [b for b in d['blocks'] if b.get('id') != 'tail']
        f.write_text(json.dumps(d, ensure_ascii=False, indent=1) + "\n", encoding='utf-8')
        print(f'  {slug}: {len(items)} карточек' +
              (f' | изделий {сводка[0]}, объектов {сводка[1]}, '
               f'{сводка[2][0]}–{сводка[2][-1]}' if сводка and сводка[2] else ''))
    print('итого карточек:', sum(len(v) for v in стр.values()))


