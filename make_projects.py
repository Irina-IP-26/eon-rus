def линейка(r):
    s = str(r.get('serv_00') or '').strip().lower()
    м = f"{r.get('Модель') or ''} {r.get('Батарея') or ''}"
    кто = f"{r.get('Клиент') or ''} {r.get('Покупатель') or ''}".upper()
    if s == 'акб' or r.get('Утяжелитель') not in (None, '', '-') or r.get('ЗУ'):
        return 'тяговые'
    if s == 'скиф' or 'СКИФ' in м.upper():
        return 'скиф'
    if re.search(r'IPBP|IPFES|-Т\b|-ТТЭ|-ТЭ\b', м):
        return 'тяговые'
    if 'Хранитель' in м or 'САЭ' in м.upper() or 'Мини-' in м:
        return 'хранитель'
    if re.search(r'Еон-Р-|Поток-|IPESS|ЭП-', м):
        # СНЭ и САЭ — синонимы, линейку решает заказчик (дом или предприятие).
        ПРЕДПРИЯТИЯ = ('ГОРИЗОНТ', 'ЮГРАЭНЕРГО', 'ТЕМИРСТРОЙ', 'РИМТЕХЭНЕРГО',
                       'МЕДЦЕНТР', 'АРДЫБАШ')
        return 'энергопоток' if any(k in кто for k in ПРЕДПРИЯТИЯ) else 'хранитель'
    return 'не определено'


