def ключ_сортировки(вручную, даты):
    """Ручная дата участвует в сортировке наравне с вычисленной."""
    if вручную:
        м = re.match(r'([а-яё]+)\s+(\d{4})', вручную)
        if м and м.group(1) in МЕСЯЦ_ИМ:
            return datetime.date(int(м.group(2)), МЕСЯЦ_ИМ.index(м.group(1)) + 1, 28)
    return даты[-1] if даты else МАЯЧОК_КЛЮЧ


def карточки(эпизоды, переим, тексты):
    правки = json.loads(ПРАВКИ.read_text(encoding='utf-8')) if ПРАВКИ.exists() else {}
    ручные_даты = правки.get('даты', {})
    разделить = правки.get('разделить', {})
    разрешено = set(правки.get('готовый_текст', {}).get('разрешено', []))
    по_страницам = collections.defaultdict(list)
    порядок = collections.Counter()
    эпизоды = sorted(эпизоды, key=lambda e: min(
        [r['_дата'] for r in e[2] if r['_дата']] or [datetime.date.min]))
    всего_у = collections.Counter((e[0], e[1]) for e in эпизоды)

    for лин, об, строки in эпизоды:
        if лин not in СТРАНИЦЫ:
            continue
        кол = sum(int(r.get('Кол_во') or 0) for r in строки)
        if кол <= 0:
            continue
        даты = [r['_дата'] for r in строки if r['_дата']]
        места = sorted({str(r.get('Место_ эксплуатации') or '').strip()
                        for r in строки if str(r.get('Место_ эксплуатации') or '').strip()})
        место = места[0] if места else ''

        порядок[(лин, об)] += 1
        имя = re.sub(r' #\d+$', '', об)
        вручную = ручные_даты.get(переим.get(об, об), {}).get('период')
        мета = ' · '.join(x for x in [
            вручную or период(даты) or МАЯЧОК,
            место if место.lower() not in имя.lower() else '',
            f'{кол} шт',
        ] if x)
        # Ключ с именем страницы: «ВСК» есть и в тяговых, и в Скифах.
        стр = СТРАНИЦЫ[лин]
        ключ_т = f'{стр}|{имя}'
        можно = всего_у[(лин, об)] == 1 and (кол == 1 or ключ_т in разрешено)
        готовый = тексты.get(ключ_т) if можно else None
        тело = готовый or текст(лин, кол, ттх(строки), строки,
                                порядок[(лин, об)], всего_у[(лин, об)], место)
        # Одна строка реестра может описывать несколько объектов сразу —
        # например два дома в одном посёлке под общим именем. Карточка
        # на объект, потому что фотография у каждого своя.
        правило = разделить.get(имя)
        подписи = правило['подписи'] if правило else [имя]
        for подпись in подписи:
            по_страницам[СТРАНИЦЫ[лин]].append({
                'title': подпись,
                'meta': мета if not правило else мета.replace(f'{кол} шт', f'{кол // правило["на"]} шт'),
                'text': (тексты.get(f'{стр}|{подпись}') if правило else None) or тело,
                'image': {'need': f'{подпись}: оборудование на объекте'},
                '_ключ': ключ_сортировки(вручную, даты),
                '_объект': f'{об}|{подпись}',
            })
    return по_страницам


