def объект(r):
    """Ключ объекта: по кому карточка.

    Имя публикуется, только если оно есть в списке организаций. Всё
    незнакомое становится «частным заказчиком» — правило перевёрнуто
    намеренно: имя частного лица не должно попасть на сайт из-за того,
    что мой распознаватель ФИО его не узнал. Новая выгрузка с новым
    заказчиком по умолчанию безымянна, пока имя не внесут в список.
    """
    кл = str(r.get('Клиент') or '').strip()
    пок = str(r.get('Покупатель') or '').strip()
    имя = кл or пок
    if not кл and пок.upper() in ДИЛЕРЫ:
        return ПЕРЕИМ.get('заказчик не записан', 'заказчик не записан')
    if имя not in ОРГАНИЗАЦИИ:
        # Разные частные дома — разные объекты, но имя на сайт не идёт.
        # Ключ анонимный и нужен только чтобы не слепить их в один.
        return 'частный заказчик #%d' % АНОНИМЫ.setdefault(имя, len(АНОНИМЫ) + 1)
    место = str(r.get('Место_ эксплуатации') or '').strip()
    # Площадки различаются графой «Клиент» (КАМАЗ) либо графой «Место»
    # (ГОРИЗОНТ, УК РОСТ). Вторую подключаем только там, где мест
    # действительно несколько, иначе один заказчик разъедется надвое.
    if имя in МНОГО_МЕСТ and место:
        имя = f'{имя} · {место}'
    # Имя сводится здесь, а не при выводе: иначе «АСАМ Спец 4» и «АСАМ Спец 5»
    # считаются разными заказчиками и дают три карточки за один декабрь.
    return ПЕРЕИМ.get(имя, имя)


